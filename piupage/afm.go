// winansiByte maps a rune to its WinAnsi (CP1252) code. ASCII and Latin-1 upper
// (0xA0..0xFF, where WinAnsi coincides with Latin-1) map directly; the
// 0x80..0x9F WinAnsi typographic glyphs are keyed by their Unicode code point.
// ok is false for a rune with no WinAnsi representation.
func winansiByte(r rune) (b byte, ok bool) {
	switch {
	case r >= 0x20 && r <= 0x7e:
		return byte(r), true
	case r >= 0xa0 && r <= 0xff:
		return byte(r), true
	}
	switch r {
	case 0x20ac:
		return 0x80, true
	case 0x201a:
		return 0x82, true
	case 0x0192:
		return 0x83, true
	case 0x201e:
		return 0x84, true
	case 0x2026:
		return 0x85, true
	case 0x2020:
		return 0x86, true
	case 0x2021:
		return 0x87, true
	case 0x02c6:
		return 0x88, true
	case 0x2030:
		return 0x89, true
	case 0x0160:
		return 0x8a, true
	case 0x2039:
		return 0x8b, true
	case 0x0152:
		return 0x8c, true
	case 0x017d:
		return 0x8e, true
	case 0x2018:
		return 0x91, true
	case 0x2019:
		return 0x92, true
	case 0x201c:
		return 0x93, true
	case 0x201d:
		return 0x94, true
	case 0x2022:
		return 0x95, true
	case 0x2013:
		return 0x96, true
	case 0x2014:
		return 0x97, true
	case 0x02dc:
		return 0x98, true
	case 0x2122:
		return 0x99, true
	case 0x0161:
		return 0x9a, true
	case 0x203a:
		return 0x9b, true
	case 0x0153:
		return 0x9c, true
	case 0x017e:
		return 0x9e, true
	case 0x0178:
		return 0x9f, true
	}
	return 0, false
}

func (f *stdFont) BaseName() string { return f.base }

func (f *stdFont) Width(r rune) float64 {
	b, ok := winansiByte(r)
	if !ok {
		b = '?'
	}
	w := f.widths[b]
	if w == 0 {
		w = f.widths['?'] // unmapped-but-present code falls back to '?'
	}
	return float64(w) / 1000
}

func (f *stdFont) Encode(dst []byte, r rune) []byte {
	b, ok := winansiByte(r)
	if !ok {
		b = '?'
	}
	return append(dst, b)
}

func (f *stdFont) writeObjects(enc *piudf.Encoder) (piudf.ObjectID, error) {
	id := enc.NewID()
	enc.BeginObject(id)
	enc.DictOpen()
	enc.Name("Type")
	enc.Name("Font")
	enc.Name("Subtype")
	enc.Name("Type1")
	enc.Name("BaseFont")
	enc.Name(f.base)
	enc.Name("Encoding")
	enc.Name("WinAnsiEncoding")
	enc.DictClose()
	enc.EndObject()
	return id, enc.Err()
}
